import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html = await readFile('index.html', 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
assert(html.includes('id="uploadForm"'));
assert(html.includes('<select id="uploadRestaurant" required disabled>'));
assert(!html.includes('const ORDERS'));
const restaurants = JSON.parse(await readFile('assets/restaurants.json', 'utf8'));
assert.equal(new Set(restaurants.map(item => item.id)).size, restaurants.length);
assert.equal(new Set(restaurants.map(item => item.name)).size, restaurants.length);
assert(restaurants.length >= 10);
const logo = await readFile('assets/artimex-logo.webp');
assert.equal(logo.subarray(0, 4).toString(), 'RIFF');
assert.equal(logo.subarray(8, 12).toString(), 'WEBP');
assert(html.includes('<title>Artimex — Portail restaurants</title>'));
assert(html.includes('id="restaurantDirectory"'));
assert(html.includes('src="/assets/artimex-logo.webp"'));
const favicon = await readFile('assets/artimex-favicon.svg', 'utf8');
assert(favicon.includes('<svg'));
console.log('Script syntax, logo and page checks passed');
